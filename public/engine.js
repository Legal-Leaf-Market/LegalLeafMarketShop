  // Returns the fixed per-CARTRIDGE gram weight for a known store's vape, else 0.
  function cartUnitG(p){
    var storeHay=String(p.store||"")+" "+String(p.storeKey||"");
    var isVape=VAPE_RE.test(String(p.name||"")) || /vape/i.test(String(p.category||""));
    if(!isVape) return 0;
    for(var i=0;i<STORE_CART_G.length;i++){
      if(STORE_CART_G[i].re.test(storeHay)) return STORE_CART_G[i].g;
    }
    return 0;
  }
  // Backfill each size row's gram value (s[2]) from the size label, then the product name.
  function normSizes(p){
    if(!p || !p.sizes || !p.sizes.length) return p;
    var nameG=0, changed=false, nm=p.name||"";
    var cartG=cartUnitG(p);                 // fixed per-cartridge weight for known vape stores (Puffy=1g)
    // Vapes/concentrates often list only a flavor per size; two sizes of the same strain then
    // look identical and merge. Force the gram weight into the LABEL so they stay distinct.
    var isVapeConc = VAPE_RE.test(nm) || /vape|concentrate/i.test(String(p.category||""));
    var sizes=p.sizes.map(function(s){
      var row=s, g=(+s[2])||0;
      if(!g){
        g=gramsFromLabel(s[0]);
        if(!g){ if(nameG===0) nameG=gramsFromName(nm); g=nameG; }
        if(!g && cartG>0){ g=cartG*packCount(String(s[0])+" "+nm); }   // Puffy vape cart default
        if(g>0){ row=s.slice(); row[2]=g; changed=true; }
      }
      // Stamp grams into the size label for vapes/concentrates when it's missing, so the
      // dropdown shows "<flavor> \u00b7 1g" vs "<flavor> \u00b7 0.5g" and dedupe never collapses them.
      if(isVapeConc && g>0 && !/\d\s*g\b/i.test(String(row[0]||""))){
        if(row===s) row=s.slice();
        var lbl=String(row[0]||"").trim();
        var gTxt=(Math.round(g*100)/100)+"g";
        row[0]= lbl ? (lbl+" \u00b7 "+gTxt) : gTxt;
        changed=true;
      }
      return row;
    });
    return changed ? Object.assign({}, p, {sizes:sizes}) : p;
  }
