  // Derive a clean strain name from a messy product title.
  function cleanStrainName(name){
    var s=String(name||"");
    s=s.replace(/\b(THCa|THC-?A|CBD|CBG|CBN|Delta[\s-]?\d+)\b/gi,"");
    s=s.replace(/\b(Flower|Pre-?roll|Prerolls?|Badder|Crumble|Live\s*Rosin|Live\s*Resin|Rosin|Resin|Distillate|Diamonds?|Vape|Cart(ridge)?|Disposable|Moonrocks?|Hash|Kief|Trim|Shake|Smalls?|Bulk|Wholesale|Sample|Gummies|Edible)\b/gi,"");
    s=s.replace(/\b(Indoor|Outdoor|Greenhouse|Light\s*(Dep|Assist)|Exotic|Premium|Budget|Value|Ultra|High|Standard|Packaged)\b/gi,"");
    s=s.replace(/\b(Indica|Sativa|Hybrid)\b/gi,"");
    s=s.replace(/[\(\)\[\]\|\u2013\u2014:].*$/,"");     // drop after first bracket/pipe/en-dash/colon
    s=s.replace(/\s[-]\s.*$/,"");                          // drop after " - " (keeps hyphenated names like Sub-Zero)
    s=s.replace(/\$?\d+(\.\d+)?\s*(g|gram|grams|oz|ounce|lb|pound|mg|%)\b/gi,""); // only numbers WITH units
    s=s.replace(/\b(0\.5|1\/8|1\/4|1\/2)\b/g,"");
    s=s.replace(/^(New!?|NEW!?)\s+/i,"");                  // strip leading "New!"
    s=s.replace(/\s{2,}/g," ").trim();
    return s || String(name||"").trim();
  }

  // Embedded COA viewer. If we found a direct COA url (PDF/image) we embed it in
  // an iframe/img right on the page. Otherwise we embed the product page (its COA
  // lives there) and also offer an "open in new tab" link.
  // Robust PDF embed: <object> renders the PDF inline where supported; if not,
  // it shows the fallback with a "download/open" link. More reliable than gview
  // for Shopify-CDN and Dropbox-hosted COAs.
  function coaPdfEmbed(url){
    // Inside the Apps Script sandboxed iframe, browsers won't inline a cross-origin
    // PDF via <object>/<iframe src=pdf>. Google's viewer fetches it server-side and
    // renders HTML, which embeds reliably. Mozilla's pdf.js is a secondary fallback.
    var gv='https://docs.google.com/viewer?embedded=true&url='+encodeURIComponent(url);
    var pj='https://mozilla.github.io/pdf.js/web/viewer.html?file='+encodeURIComponent(url);
    return '<iframe class="coaframe" src="'+esc(gv)+'" loading="lazy" '
      +'onload="this.dataset.ok=1" '
      +'onerror="this.src=\''+esc(pj)+'\'"></iframe>'
      +'<div class="coahint">Loading the COA\u2026 if it doesn\u2019t appear, '
      +'<a class="coalink" href="'+esc(url)+'" target="_blank" rel="noopener">open it in a new tab \u2197</a></div>';
  }

