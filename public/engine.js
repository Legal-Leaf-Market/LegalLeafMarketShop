  // Group products that are the SAME strain within the SAME store into a single
  // card whose size dropdown spans all their variants. This is our own
  // normalization - it dedupes "Berry Pie 3.5g / 7g / 14g" style listings into
  // one clean card even when the store lists them separately.
  function groupByStrain(list){
    var groups={}, order=[];
    list.forEach(function(p){
      // Accessories/glass have no strain at all -- strainFacet() only rejects
      // vocabulary it recognizes as junk, and the gear catalogue (~1,500 products
      // across six stores) says plenty of names it does not, so a glass or
      // grinder listing could pick up a bogus "strain" and merge with an
      // unrelated product that happened to produce the same one.
      var strain=prodIsGlass(p)?"":strainFacet(p.name);
      // Only group when we have a real strain name; otherwise keep as-is (unique key).
      var key = strain ? (p.storeKey+"||"+strain.toLowerCase()+"||"+p.category)
                       : ("__solo__"+(p.id));
      if(!groups[key]){ groups[key]={base:p, strain:strain, sizes:[], img:"", anyIn:false}; order.push(key); }
      var g=groups[key];
      // carry each size row with ITS product url (for checkout) AND its image
      // (so selecting a different strain in a grouped dropdown swaps the photo).
      (p.sizes||[]).forEach(function(s){
        g.sizes.push([s[0],s[1],s[2],s[3],s[4]!==false,p.url||g.base.url,s[6]||p.image||""]);
        if(s[4]!==false) g.anyIn=true;
      });
      if(!g.img && p.image) g.img=p.image;
      // prefer a shorter/cleaner display base
      if(p.name.length < g.base.name.length) g.base=p;
    });
    return order.map(function(key){
      var g=groups[key];
      if(g.sizes.length<=1 && !g.strain){ return g.base; } // untouched solo
      // dedupe identical size rows (same label+price)
      var seen={}, sizes=[];
      g.sizes.forEach(function(s){var k=s[0]+"|"+s[1];if(!seen[k]){seen[k]=1;sizes.push(s);}});
      // recompute best price / $g from in-stock pool
      var pool=sizes.filter(function(s){return s[4];}); if(!pool.length) pool=sizes;
      var minP=Infinity, bestPerG=null, startsAt=g.base.startsAt||0;
      pool.forEach(function(s){ if(s[1]<minP)minP=s[1]; if(s[2]>0){var pg=s[1]/s[2]; if(bestPerG===null||pg<bestPerG)bestPerG=pg;} });
      var b=g.base;
      // union badges across the group
      var badges=b.badges?b.badges.slice():[];
      // display name: clean strain (Title) if we have it, else original
      var disp = g.strain || b.name;
      return Object.assign({}, b, {
        name: disp,
        image: g.img||b.image,
        sale: Math.round(minP*100)/100,
        startsAt: startsAt>minP?startsAt:minP,
        perG: bestPerG!==null?Math.round(bestPerG*100)/100:b.perG,
        inStock: g.anyIn,
        badges: badges,
        grouped: sizes.length>1,
        variants: sizes.length,
        sizes: sizes
      });
    });
  }

