  function storeCheckoutUrl(domain, items){
    const first = items[0]||{};
    // Greek Glass = Big Cartel: no multi-item cart permalink exists, so it is handled
    // by the ggCheckout() bookmarklet-handoff modal, NOT a URL. Signal that here.
    if(first.storeKey==="greekglass" || first.platform==="bigcartel") return null;
    // refLink early-return removed 2026-08-08: DSquared's /ctieyqlp slug died in the
    // Cielo rebrand (404), and it threw the whole cart away for a landing page anyway.
    const qs=[];
    if(first.coupon) qs.push("discount="+encodeURIComponent(first.coupon));
    if(first.ref)    qs.push((first.refParam||"ref")+"="+encodeURIComponent(first.ref));
    const q = qs.length?("?"+qs.join("&")):"";
    const plat = first.platform||"shopify";
    if(plat==="woocommerce"){
      // Pre-fill via ?add-to-cart when an item carries a Woo id (variation id, or product
      // id on simple products). The cart path copies the permalink's trailing-slash style:
      // the wrong style 301s and Woo replays add-to-cart on the redirect, doubling the
      // quantity (measured live on Binoid and YLLVAPE, in opposite directions). Items
      // without an id fall back to the product page -- a variable parent id fills nothing.
      const it=items.find(i=>i.variantId)||null;
      const pu=(it&&it.url)||first.url||("https://"+domain+"/");
      let u = it ? ("https://"+domain+(pu.split("?")[0].slice(-1)==="/"?"/cart/":"/cart")+"?add-to-cart="+encodeURIComponent(it.variantId)) : pu;
      if(first.coupon) u+=(u.indexOf("?")>=0?"&":"?")+"coupon_code="+encodeURIComponent(first.coupon);
      if(it&&first.ref) u+="&"+(first.refParam||"ref")+"="+encodeURIComponent(first.ref);
      return u;
    }
    if(plat==="webflow" || plat==="bigcommerce" || plat==="squarespace"){
      // Scraped stores without variant IDs: send to the product page (carries ?ref=).
      let u=first.url||("https://"+domain+"/");
      return u;
    }
    // Shopify cart. Use cartDomain when the checkout host differs from the display
    // host (e.g. Black Tie: links on www.blacktiecbd.net, cart on the myshopify host).
    const cartHost = first.cartDomain || domain;
    const line = items.filter(i=>i.variantId).map(i=>i.variantId+":1").join(",");
    if(line) return "https://"+cartHost+"/cart/"+line+q;        // Shopify add-to-cart + coupon + ref
    return "https://"+cartHost+"/"+q;                             // fallback: store home w/ ref
  }
