  function normCannabinoid(p){
    if(!p) return p;
    var name=String(p.name||"");
    // BOTANICAL: Binoid's ENTIRE "Active Flowers Line" (lavender, chamomile, pink lotus,
    // etc.) is botanical-infused — its own cannabinoid type, not THCa/CBD. Front-end
    // authoritative so the chip always shows "Botanical" for every scent in the line.
    if(/active\s*flowers?/i.test(name)) return Object.assign({}, p, {cannabinoid:"Botanical"});
    var thc=0, cbd=0, re=/([\d.]+)\s*mg\s*(thca?|delta[\s-]?9|d9|cbd|cbg|cbn|cbc|cbda)/gi, mm;
    while((mm=re.exec(name))){
      var v=parseFloat(mm[1]), c=mm[2].toLowerCase();
      if(/thc|delta|d9/.test(c)) thc=Math.max(thc,v); else cbd=Math.max(cbd,v);
    }
    if(thc>0 && thc>cbd && String(p.cannabinoid||"").toUpperCase()==="CBD"){
      return Object.assign({}, p, {cannabinoid:"THC"});   // THC-dominant -> not a CBD product
    }
    return p;
  }
